/*
 * Builds the canvas web view: one self-contained page, script, styles and Inter inlined, as
 * dist/index.html, and dist/bundle.ts, which exports it as a string for `source={{ html }}`.
 *
 *   bun apps/mobile/canvas/build.ts
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import type { BunPlugin } from "bun";

const here = import.meta.dir;
const repo = resolve(here, "../../..");
const dist = join(here, "dist");
// The app's own React is React Native's, a different version: the web view and the desktop
// pieces it reuses share @ponzu/react's.
const reactHome = join(repo, "packages/react/node_modules");
const oneReact: BunPlugin = {
  name: "one-react",
  setup(build) {
    build.onResolve({ filter: /^(react|react-dom)(\/.*)?$/ }, (args) => ({
      path: Bun.resolveSync(args.path, reactHome),
    }));
  },
};

const result = await Bun.build({
  entrypoints: [join(here, "index.tsx")],
  target: "browser",
  minify: true,
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  plugins: [oneReact],
});
if (!result.success) throw new AggregateError(result.logs, "Canvas build failed");
const script = (await result.outputs[0]!.text()).replaceAll("</script", "<\\/script");

/**
 * Inter for labels and pins, embedded: a web view can't see the fonts the app loads, and the
 * canvas's own labels shouldn't wait on Google. Designs' fonts still come from Google, as on
 * desktop. 500 and 600 are the weights it draws; fonts/ has them cut to Latin (see README).
 */
async function inter(weight: 500 | 600) {
  const bytes = await readFile(join(here, `fonts/inter-${weight}.woff`));
  return `@font-face{font-family:Inter;font-style:normal;font-weight:${weight};font-display:block;src:url(data:font/woff;base64,${bytes.toString("base64")}) format("woff")}`;
}
const fonts = (await inter(500)) + (await inter(600));
const css = (await readFile(join(here, "canvas.css"), "utf8")).replace(/\/\*[\s\S]*?\*\//g, "");

const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover"><style>${fonts}</style><style>${css}</style></head><body><div id="root"></div><script type="module">${script}</script></body></html>`;

await mkdir(dist, { recursive: true });
await writeFile(join(dist, "index.html"), html);
await writeFile(
  join(dist, "bundle.ts"),
  `// Generated by apps/mobile/canvas/build.ts. Don't edit.\nexport const canvasHtml = ${JSON.stringify(html)};\n`,
);
console.log(`canvas: dist/index.html ${(html.length / 1024).toFixed(0)} KB`);
