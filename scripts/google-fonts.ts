/**
 * Regenerates packages/render/src/google-fonts-data.ts from Google Fonts'
 * public metadata: every family with the weights and italics it really has,
 * so a font request asks only for what exists (Google answers 400 to anything
 * else). Run it now and then to pick up new families:
 *
 *   bun scripts/google-fonts.ts           # regenerate
 *   bun scripts/google-fonts.ts --check   # also ask Google to accept every family's request
 */
import { writeFile } from "node:fs/promises";
import { join } from "node:path";

interface Family {
  family: string;
  fonts: Record<string, unknown>;
  axes?: { tag: string; min: number; max: number }[];
}

const res = await fetch("https://fonts.google.com/metadata/fonts");
if (!res.ok) throw new Error(`metadata: ${res.status}`);
const raw = (await res.text()).replace(/^\)\]\}'\s*/, "");
const families = (JSON.parse(raw) as { familyMetadataList: Family[] }).familyMetadataList;

const lines: string[] = [];
for (const f of [...families].sort((a, b) => a.family.localeCompare(b.family))) {
  if (/[;\n`$\\]/.test(f.family)) continue;
  const keys = Object.keys(f.fonts);
  const upright = keys.filter((k) => !k.endsWith("i")).map(Number);
  const italic = keys.filter((k) => k.endsWith("i")).map((k) => Number(k.slice(0, -1)));
  const wght = f.axes?.find((a) => a.tag === "wght");
  // A weight axis serves every weight in its range, upright and italic alike.
  const range = wght ? `${wght.min}..${wght.max}` : null;
  const list = (ws: number[]) => [...new Set(ws)].sort((a, b) => a - b).join(",");
  const u = upright.length ? (range ?? list(upright)) : "";
  const i = italic.length ? (range ?? list(italic)) : "";
  lines.push(u === "400" && !i ? f.family : `${f.family};${u}${i ? `;${i}` : ""}`);
}

const out = `// Generated by scripts/google-fonts.ts from fonts.google.com/metadata/fonts. Don't edit.
// One family per line: "Name;upright weights;italic weights". "100..900" is a
// variable weight axis; a bare name has only an upright 400.
export const GOOGLE_FONTS_DATA = \`
${lines.join("\n")}
\`;
`;
const path = join(import.meta.dir, "../packages/render/src/google-fonts-data.ts");
await writeFile(path, out);
console.log(`Wrote ${lines.length} families to ${path}`);

if (process.argv.includes("--check")) {
  // A combined request fails as a whole if any one family's axes are wrong.
  const { googleFontRequest } = await import("../packages/render/src/fonts.ts");
  const names = lines.map((l) => l.split(";")[0]!);
  const bad: string[] = [];
  const check = async (batch: string[]): Promise<void> => {
    const q = batch.map((n) =>
      googleFontRequest(n)
        .href.split("?")[1]!
        .replace(/&display=.*$/, ""),
    );
    const r = await fetch(`https://fonts.googleapis.com/css2?${q.join("&")}`);
    if (r.ok) return;
    if (batch.length === 1) bad.push(batch[0]!);
    else {
      const mid = batch.length >> 1;
      await Promise.all([check(batch.slice(0, mid)), check(batch.slice(mid))]);
    }
  };
  for (let i = 0; i < names.length; i += 200)
    await Promise.all(
      Array.from({ length: 8 }, (_, j) =>
        check(names.slice(i + j * 25, i + (j + 1) * 25)).catch(() => {}),
      ),
    );
  console.log(bad.length ? `Google rejected: ${bad.join(", ")}` : "Google accepts every family.");
  process.exit(bad.length ? 1 : 0);
}
